/** Getting work out: still, vector, motion, data, and the parameters themselves. */
import type { Params } from './params';
import { defaults, speciesById } from './params';
import { hexToRGB } from './render';
import { DEAD, SENESCENT, type Sim } from './sim';

function save(blob: Blob, name: string): void {
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = name;
  document.body.appendChild(a); a.click(); a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 4000);
}

export const stamp = (): string =>
  new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);

export function exportPNG(canvas: HTMLCanvasElement, scale: number, name: string): void {
  const out = document.createElement('canvas');
  out.width = canvas.width * scale;
  out.height = canvas.height * scale;
  const c = out.getContext('2d')!;
  c.imageSmoothingEnabled = false;                 // keep the dither grid hard
  c.drawImage(canvas, 0, 0, out.width, out.height);
  out.toBlob((b) => b && save(b, `${name}.png`), 'image/png');
}

/**
 * Cells as real geometry. The dither is a raster operation and deliberately
 * has no vector equivalent, so this is the culture, not the photograph of it.
 */
export function exportSVG(sim: Sim, p: Params, w: number, h: number, name: string): void {
  const sp = speciesById(p.species);
  const baseR = sp.radius * p.cellScale * 4;
  const paper = p.invert ? hexToRGB(p.inkColor) : hexToRGB(p.paperColor);
  const ink = p.invert ? hexToRGB(p.paperColor) : hexToRGB(p.inkColor);
  const rgb = (c: number[]) => `rgb(${c[0]},${c[1]},${c[2]})`;

  const parts: string[] = [];
  parts.push(`<rect width="${w}" height="${h}" fill="${rgb(paper)}"/>`);
  const groups: Record<string, string[]> = { alive: [], senescent: [], dead: [] };

  for (const c of sim.cells) {
    const r = (baseR * Math.sqrt(Math.max(0.05, c.size))).toFixed(2);
    const x = c.x.toFixed(2), y = c.y.toFixed(2);
    const key = c.state === DEAD ? 'dead' : c.state === SENESCENT ? 'senescent' : 'alive';
    if (sp.shape === 'rod' || sp.shape === 'filament' || sp.shape === 'hypha') {
      const L = Number(r) * (sp.shape === 'filament' ? 2.6 : 1.5) * Math.max(1, c.size) * 0.5;
      const x1 = (c.x - Math.cos(c.angle) * L).toFixed(2), y1 = (c.y - Math.sin(c.angle) * L).toFixed(2);
      const x2 = (c.x + Math.cos(c.angle) * L).toFixed(2), y2 = (c.y + Math.sin(c.angle) * L).toFixed(2);
      groups[key].push(`<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke-width="${Number(r) * 2}"/>`);
    } else {
      groups[key].push(`<circle cx="${x}" cy="${y}" r="${r}"/>`);
    }
  }
  const tone: Record<string, string> = { dead: '0.28', senescent: '0.6', alive: '1' };
  for (const k of ['dead', 'senescent', 'alive']) {
    if (!groups[k].length) continue;
    parts.push(`<g fill="${rgb(ink)}" stroke="${rgb(ink)}" stroke-linecap="round" opacity="${tone[k]}">${groups[k].join('')}</g>`);
  }
  if (p.accent !== 'none') parts.push(`<!-- accent channel: ${p.accent} -->`);

  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}">
<title>AGAR culture — ${p.text.replace(/[<&>]/g, '')} — t+${(sim.t / 60).toFixed(1)}h</title>
<desc>${sim.cells.length} cells of ${sp.label}, ${sim.phase} phase. Generated by AGAR.</desc>
${parts.join('\n')}
</svg>`;
  save(new Blob([svg], { type: 'image/svg+xml' }), `${name}.svg`);
}

export function exportCSV(sim: Sim, name: string): void {
  const rows = ['t_minutes,t_hours,population,mean_substrate,mean_growth_rate,mean_speed_trait,mean_resistance'];
  for (const s of sim.samples) {
    rows.push([s.t.toFixed(1), (s.t / 60).toFixed(3), s.pop, s.sub.toFixed(5), s.mu.toFixed(5), s.speed.toFixed(5), s.res.toFixed(5)].join(','));
  }
  save(new Blob([rows.join('\n')], { type: 'text/csv' }), `${name}-timeseries.csv`);
}

export function exportPreset(p: Params, name: string): void {
  save(new Blob([JSON.stringify({ agar: 1, params: p }, null, 2)], { type: 'application/json' }), `${name}-preset.json`);
}

export async function importPreset(file: File): Promise<Partial<Params>> {
  const text = await file.text();
  const json = JSON.parse(text);
  const src = json?.params ?? json;
  const out: Record<string, unknown> = {};
  for (const k of Object.keys(defaults)) if (k in src) out[k] = src[k];
  return out as Partial<Params>;
}

/** Share link: only the parameters that differ from the defaults. */
export function shareURL(p: Params): string {
  const diff: Record<string, unknown> = {};
  for (const k of Object.keys(defaults) as (keyof Params)[]) {
    if (p[k] !== defaults[k]) diff[k] = p[k];
  }
  const b64 = btoa(unescape(encodeURIComponent(JSON.stringify(diff))));
  return `${location.origin}${location.pathname}#p=${b64}`;
}

export function readURL(): Partial<Params> | null {
  const m = /#p=(.+)$/.exec(location.hash);
  if (!m) return null;
  try {
    const json = JSON.parse(decodeURIComponent(escape(atob(m[1]))));
    const out: Record<string, unknown> = {};
    for (const k of Object.keys(defaults)) if (k in json) out[k] = json[k];
    return out as Partial<Params>;
  } catch { return null; }
}

export class Recorder {
  private rec: MediaRecorder | null = null;
  private chunks: Blob[] = [];
  get active(): boolean { return this.rec !== null; }

  start(canvas: HTMLCanvasElement, fps = 30): boolean {
    if (this.rec || typeof MediaRecorder === 'undefined') return false;
    const stream = canvas.captureStream(fps);
    const type = ['video/webm;codecs=vp9', 'video/webm;codecs=vp8', 'video/webm']
      .find((t) => MediaRecorder.isTypeSupported(t));
    if (!type) return false;
    this.chunks = [];
    this.rec = new MediaRecorder(stream, { mimeType: type, videoBitsPerSecond: 12_000_000 });
    this.rec.ondataavailable = (e) => { if (e.data.size) this.chunks.push(e.data); };
    this.rec.start(200);
    return true;
  }

  stop(name: string): void {
    const rec = this.rec;
    if (!rec) return;
    rec.onstop = () => save(new Blob(this.chunks, { type: 'video/webm' }), `${name}.webm`);
    rec.stop();
    this.rec = null;
  }
}
